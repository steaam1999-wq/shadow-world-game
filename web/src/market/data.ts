export function priceLabel(l: Pick<Listing, 'price' | 'exchange'>) {
  if (!l.price) return 'Бесплатно'
  return `${l.price.toLocaleString('ru-RU')} ₽${l.exchange ? ' · обмен' : ''}`
}

/** «5 мин назад», «2 ч назад», «вчера», «3 дня назад» */
export function ago(ts: number, now = Date.now()) {
  const m = Math.max(1, Math.round((now - ts) / 60_000))
  if (m < 60) return `${m} мин назад`
  const h = Math.round(m / 60)
  if (h < 24) return `${h} ч назад`
  const d = Math.round(h / 24)
  if (d === 1) return 'вчера'
  return `${d} ${d < 5 ? 'дня' : 'дней'} назад`
}
